package com.group32.cs261project.frontend;

/**
 * Enumeration representing the different navigation states of the application.
 *
 * Each value corresponds to a specific page shown in the user interface.
 * The application switches between these states to control which page
 * is currently displayed.
 */
public enum AppState {
    CONFIGURE,
    RUNNING,
    RESULTS,
    COMPARE,
    COMPARE_HISTORY
}